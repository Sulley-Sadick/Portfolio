-- contact_messages: schema (idempotent) + RLS lockdown.
-- Inserts are performed only by Edge Functions using the service role.
-- Anon / authenticated clients have no direct table access.

create extension if not exists pg_net with schema extensions;

create table if not exists public.contact_messages (
  id bigint generated by default as identity primary key,
  name text not null,
  contact text not null,
  message text not null,
  client_ip_hash text,
  created_at timestamptz not null default now()
);

alter table public.contact_messages
  add column if not exists client_ip_hash text;

alter table public.contact_messages
  add column if not exists created_at timestamptz;

update public.contact_messages
set created_at = coalesce(created_at, now())
where created_at is null;

alter table public.contact_messages
  alter column created_at set default now();

do $$
begin
  alter table public.contact_messages
    alter column created_at set not null;
exception
  when others then
    null;
end;
$$;

create index if not exists contact_messages_created_at_idx
  on public.contact_messages (created_at desc);

create index if not exists contact_messages_ip_hash_created_at_idx
  on public.contact_messages (client_ip_hash, created_at desc);

comment on table public.contact_messages is
  'Portfolio contact form submissions. Writable only via service role (submit-contact Edge Function).';

comment on column public.contact_messages.client_ip_hash is
  'SHA-256 hex digest of the submitter IP for rate limiting; raw IP is not stored.';

alter table public.contact_messages enable row level security;

-- No policies for anon/authenticated → all direct client access denied under RLS.
-- service_role bypasses RLS (BYPASSRLS) and remains usable from Edge Functions.

revoke all on table public.contact_messages from anon, authenticated;
grant all on table public.contact_messages to service_role;

-- Identity sequences (if present) must not be usable by public API roles.
do $$
declare
  seq_name text;
begin
  select pg_get_serial_sequence('public.contact_messages', 'id') into seq_name;
  if seq_name is not null then
    execute format('revoke all on sequence %s from anon, authenticated', seq_name);
    execute format('grant usage, select on sequence %s to service_role', seq_name);
  end if;
end;
$$;
